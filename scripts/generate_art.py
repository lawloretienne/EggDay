#!/usr/bin/env python3
"""Generates Egg Day's vector art from one set of shapes.

Writes Android vector drawables to app/src/main/res/drawable and the Play Store
icon SVG to art/. Run from the repo root:

    python3 scripts/generate_art.py [--preview DIR]

--preview also writes SVG versions of every drawable to DIR for a quick look.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRAWABLE = os.path.join(ROOT, "app/src/main/res/drawable")
ART = os.path.join(ROOT, "art")

# 5x7 dot-matrix glyphs, like the inkjet printers that stamp pack dates on cartons.
GLYPHS = {
    "0": ["01110", "10001", "10001", "10001", "10001", "10001", "01110"],
    "1": ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
    "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
    "3": ["11111", "00010", "00100", "00010", "00001", "10001", "01110"],
    "4": ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
    "5": ["11111", "10000", "11110", "00001", "00001", "10001", "01110"],
    "6": ["00110", "01000", "10000", "11110", "10001", "10001", "01110"],
    "7": ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
    "8": ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
    "9": ["01110", "10001", "10001", "01111", "00001", "00010", "01100"],
    "P": ["11110", "10001", "10001", "11110", "10000", "10000", "10000"],
    "-": ["00000", "00000", "00000", "11111", "00000", "00000", "00000"],
}
DOT_RADIUS = 0.42  # in grid units; 0.5 would make neighboring dots touch

# Egg geometry, in a 100 x 136 box (the egg plus room for its shadow).
EGG_W, EGG_H = 100, 136
EGG_PATH = "M50,4 C74,4 92,44 92,78 C92,104 73,124 50,124 C27,124 8,104 8,78 C8,44 26,4 50,4 Z"
SHADOW = (50, 125, 30, 5)  # cx, cy, rx, ry
SPECKLES = [  # cx, cy, rx, ry; kept clear of the stamped number (x 14-86, y 64-96)
    (36, 22, 1.6, 1.2), (58, 16, 1.2, 1.0), (66, 30, 1.8, 1.3), (44, 34, 1.1, 0.9),
    (28, 48, 1.5, 1.1), (74, 50, 1.3, 1.0), (55, 46, 1.7, 1.2), (16, 56, 1.2, 1.0),
    (80, 114, 1.4, 1.1), (24, 102, 1.6, 1.2), (48, 110, 1.2, 1.0), (70, 104, 1.7, 1.2),
    (80, 62, 1.0, 0.8), (38, 58, 1.0, 0.8),
]
HIGHLIGHT = (34, 38, 11, 19, -25)  # cx, cy, rx, ry, rotation
# Where the day number sits on the egg. EggArt.kt mirrors these fractions.
STAMP_CENTER_Y = 80
STAMP_DIGIT_H = 28
STAMP_GAP = 0.16  # gap between digits, as a fraction of digit height


def ellipse(cx, cy, rx, ry):
    return (f"M{cx - rx:g},{cy:g} a{rx:g},{ry:g} 0 1,0 {2 * rx:g},0 "
            f"a{rx:g},{ry:g} 0 1,0 {-2 * rx:g},0 Z")


def dots_path(text, x, y, pitch):
    """Path of dot-matrix text whose top-left corner is (x, y)."""
    parts = []
    r = DOT_RADIUS * pitch
    for i, ch in enumerate(text):
        ox = x + i * 6 * pitch  # 5 columns + 1 column of spacing
        for row, bits in enumerate(GLYPHS[ch]):
            for col, bit in enumerate(bits):
                if bit == "1":
                    parts.append(ellipse(round(ox + (col + 0.5) * pitch, 3),
                                         round(y + (row + 0.5) * pitch, 3), round(r, 3), round(r, 3)))
    return " ".join(parts)


def stamp_path(text, h=STAMP_DIGIT_H, gap_ratio=STAMP_GAP, center_y=STAMP_CENTER_Y):
    """Day number stamped on the egg, in egg coordinates."""
    pitch = h / 7
    gap = gap_ratio * h
    width = len(text) * 5 * pitch + (len(text) - 1) * gap
    x0 = EGG_W / 2 - width / 2
    parts = []
    for i, ch in enumerate(text):
        parts.append(dots_path(ch, x0 + i * (5 * pitch + gap), center_y - h / 2, pitch))
    return " ".join(parts)


# Shapes are (kind, data) tuples rendered by both the vector-drawable and SVG writers.
def egg_shapes(shell, speckle, shadow, highlight=True):
    shapes = [
        ("path", {"d": ellipse(*SHADOW), "fill": shadow}),
        ("path", {"d": EGG_PATH, "fill": shell}),
        ("path", {"d": " ".join(ellipse(*s) for s in SPECKLES), "fill": speckle}),
    ]
    if highlight:
        cx, cy, rx, ry, rot = HIGHLIGHT
        shapes.append(("group", {"rotate": (rot, cx, cy), "children": [
            ("path", {"d": ellipse(cx, cy, rx, ry), "radial": (cx, cy, ry, "#66FFFFFF", "#00FFFFFF")}),
        ]}))
    return shapes


# ---- writers -----------------------------------------------------------------

def argb_to_svg(color):
    """'#AARRGGBB' or '#RRGGBB' -> (svg color, opacity)."""
    c = color.lstrip("#")
    if len(c) == 8:
        return "#" + c[2:], int(c[:2], 16) / 255
    return "#" + c, 1.0


def vector_xml(width_dp, height_dp, vw, vh, shapes, tint=None):
    needs_aapt = any("radial" in str(s) for s in shapes)
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by scripts/generate_art.py. Edit the script, not this file. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"'
           + ('\n    xmlns:aapt="http://schemas.android.com/aapt"' if needs_aapt else ""),
           f'    android:width="{width_dp}dp"',
           f'    android:height="{height_dp}dp"',
           f'    android:viewportWidth="{vw:g}"',
           f'    android:viewportHeight="{vh:g}"' + (f'\n    android:tint="{tint}"' if tint else "") + ">"]

    def emit(items, indent):
        pad = " " * indent
        for kind, d in items:
            if kind == "group":
                attrs = []
                if "rotate" in d:
                    rot, px, py = d["rotate"]
                    attrs += [f'android:rotation="{rot:g}"', f'android:pivotX="{px:g}"', f'android:pivotY="{py:g}"']
                if "translate" in d:
                    attrs += [f'android:translateX="{d["translate"][0]:g}"', f'android:translateY="{d["translate"][1]:g}"']
                if "scale" in d:
                    attrs += [f'android:scaleX="{d["scale"]:g}"', f'android:scaleY="{d["scale"]:g}"']
                out.append(f"{pad}<group " + f"\n{pad}    ".join(attrs) + ">")
                emit(d["children"], indent + 4)
                out.append(f"{pad}</group>")
                continue
            extra = ""
            if d.get("evenOdd"):
                extra += f'\n{pad}    android:fillType="evenOdd"'
            if "stroke" in d:
                extra += (f'\n{pad}    android:strokeColor="{d["stroke"]}"'
                          f'\n{pad}    android:strokeWidth="{d["strokeWidth"]:g}"')
            if "radial" in d:
                cx, cy, r, c0, c1 = d["radial"]
                out.append(f'{pad}<path android:pathData="{d["d"]}">')
                out.append(f'{pad}    <aapt:attr name="android:fillColor">')
                out.append(f'{pad}        <gradient android:type="radial" android:centerX="{cx:g}" '
                           f'android:centerY="{cy:g}" android:gradientRadius="{r:g}" '
                           f'android:startColor="{c0}" android:endColor="{c1}" />')
                out.append(f"{pad}    </aapt:attr>")
                out.append(f"{pad}</path>")
            else:
                fill = f'\n{pad}    android:fillColor="{d["fill"]}"' if d.get("fill") else ""
                out.append(f'{pad}<path{fill}{extra}\n{pad}    android:pathData="{d["d"]}" />')

    emit(shapes, 4)
    out.append("</vector>")
    return "\n".join(out) + "\n"


def svg(vw, vh, shapes, size=None, background=None, resolve=lambda c: c):
    size = size or (vw, vh)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{size[0]}" height="{size[1]}" '
           f'viewBox="0 0 {vw:g} {vh:g}">', "<defs>"]
    body = []
    grad = [0]
    if background:
        body.append(f'<rect width="{vw:g}" height="{vh:g}" fill="{background}"/>')

    def emit(items):
        for kind, d in items:
            if kind == "group":
                t = []
                if "translate" in d:
                    t.append(f'translate({d["translate"][0]:g} {d["translate"][1]:g})')
                if "scale" in d:
                    t.append(f'scale({d["scale"]:g})')
                if "rotate" in d:
                    t.append("rotate({:g} {:g} {:g})".format(*d["rotate"]))
                body.append(f'<g transform="{" ".join(t)}">')
                emit(d["children"])
                body.append("</g>")
                continue
            attrs = []
            if "radial" in d:
                cx, cy, r, c0, c1 = d["radial"]
                grad[0] += 1
                gid = f"g{grad[0]}"
                (s0, o0), (s1, o1) = argb_to_svg(c0), argb_to_svg(c1)
                out.append(f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{cx:g}" cy="{cy:g}" r="{r:g}">'
                           f'<stop offset="0" stop-color="{s0}" stop-opacity="{o0:.2f}"/>'
                           f'<stop offset="1" stop-color="{s1}" stop-opacity="{o1:.2f}"/></radialGradient>')
                attrs.append(f'fill="url(#{gid})"')
            elif d.get("fill"):
                c, o = argb_to_svg(resolve(d["fill"]))
                attrs.append(f'fill="{c}" fill-opacity="{o:.2f}"')
            else:
                attrs.append('fill="none"')
            if d.get("evenOdd"):
                attrs.append('fill-rule="evenodd"')
            if "stroke" in d:
                c, o = argb_to_svg(resolve(d["stroke"]))
                attrs.append(f'stroke="{c}" stroke-opacity="{o:.2f}" stroke-width="{d["strokeWidth"]:g}"')
            body.append(f'<path d="{d["d"]}" {" ".join(attrs)}/>')

    emit(shapes)
    out.append("</defs>")
    return "\n".join(out + body + ["</svg>"]) + "\n"


# ---- art ---------------------------------------------------------------------

# Colors for art that can't use resources (launcher icon, Play icon, previews).
SHELL, SPECKLE, SHADOW_C, INK = "#E5C2A3", "#C9A27F", "#33000000", "#3A2615"
ICON_BG = "#7A5638"  # brown, so the light egg stands out
CARTON, CARTON_EDGE, ACCENT = "#EFE6D8", "#BBA78F", "#7A5638"
PREVIEW_COLORS = {"@color/egg_shell": SHELL, "@color/egg_speckle": SPECKLE,
                  "@color/egg_shadow": SHADOW_C, "@color/egg_ink": INK}


# Launcher icon: no shadow (launchers add their own), so the egg (y 4-124) can fill the
# adaptive icon's 66dp safe zone, with a larger number so it reads at icon size.
ICON_SCALE = 0.49
ICON_STAMP = dict(h=29, gap_ratio=0.16, center_y=80)


def _icon_group(children):
    tx, ty = 54 - EGG_W * ICON_SCALE / 2, 54 - 64 * ICON_SCALE
    return [("group", {"translate": (round(tx, 2), round(ty, 2)), "scale": ICON_SCALE, "children": children})]


def icon_foreground_shapes(number="365"):
    return _icon_group(egg_shapes(SHELL, SPECKLE, None)[1:]
                       + [("path", {"d": stamp_path(number, **ICON_STAMP), "fill": INK})])


def icon_monochrome_shapes(number="365"):
    # Egg silhouette with the number punched out; launchers tint it for themed icons.
    return _icon_group([("path", {"d": EGG_PATH + " " + stamp_path(number, **ICON_STAMP),
                                  "fill": "#FF000000", "evenOdd": True})])


def carton_shapes():
    bumps = " ".join(ellipse(cx, 30, 20, 16) for cx in (52, 120, 188))
    pitch_code, pitch_date = 2.4, 3.2
    date_w = 3 * 5 * pitch_date + 2 * pitch_date
    date_x = 150
    return [
        ("path", {"d": bumps, "fill": CARTON, "stroke": CARTON_EDGE, "strokeWidth": 2}),
        ("path", {"d": "M16,28 H224 a8,8 0 0 1 8,8 V96 a8,8 0 0 1 -8,8 H16 a8,8 0 0 1 -8,-8 V36 a8,8 0 0 1 8,-8 Z",
                  "fill": CARTON, "stroke": CARTON_EDGE, "strokeWidth": 2}),
        ("path", {"d": dots_path("P-1970", 26, 58, pitch_code), "fill": INK}),
        ("path", {"d": dots_path("293", date_x, 55, pitch_date), "fill": INK}),
        ("path", {"d": f"M{date_x - 8},47 h{date_w + 16:g} a6,6 0 0 1 6,6 v26 a6,6 0 0 1 -6,6 "
                       f"h{-(date_w + 16):g} a6,6 0 0 1 -6,-6 v-26 a6,6 0 0 1 6,-6 Z",
                  "stroke": ACCENT, "strokeWidth": 3}),
    ]


def main():
    preview = sys.argv[sys.argv.index("--preview") + 1] if "--preview" in sys.argv else None
    os.makedirs(DRAWABLE, exist_ok=True)
    os.makedirs(ART, exist_ok=True)
    files = {}

    # Egg layers use color resources so night mode picks darker shell colors.
    files["egg.xml"] = (100, 136, EGG_W, EGG_H,
                        egg_shapes("@color/egg_shell", "@color/egg_speckle", "@color/egg_shadow"), None)
    for ch in "0123456789":
        files[f"dm_{ch}.xml"] = (10, 14, 5, 7, [("path", {"d": dots_path(ch, 0, 0, 1), "fill": "@color/egg_ink"})], None)
    files["carton_end.xml"] = (240, 112, 240, 112, carton_shapes(), None)
    files["ic_egg.xml"] = (24, 24, 24, 24, [("group", {"translate": (4, 1), "scale": 0.16, "children": [
        ("path", {"d": EGG_PATH, "fill": "#FFFFFFFF"})]})], "?android:attr/colorControlNormal")
    files["ic_launcher_foreground.xml"] = (108, 108, 108, 108, icon_foreground_shapes(), None)
    files["ic_launcher_monochrome.xml"] = (108, 108, 108, 108, icon_monochrome_shapes(), None)

    for name, (w, h, vw, vh, shapes, tint) in files.items():
        with open(os.path.join(DRAWABLE, name), "w") as f:
            f.write(vector_xml(w, h, vw, vh, shapes, tint))
        if preview:
            with open(os.path.join(preview, name.replace(".xml", ".svg")), "w") as f:
                side = max(vw, vh) * 4  # square, so Quick Look thumbnails letterbox instead of cropping
                f.write(svg(vw, vh, shapes, size=(side, side), resolve=lambda c: PREVIEW_COLORS.get(c, c)))

    play = svg(108, 108, icon_foreground_shapes(), size=(512, 512), background=ICON_BG)
    with open(os.path.join(ART, "play-icon.svg"), "w") as f:
        f.write(play)
    if preview:
        stamped = egg_shapes(SHELL, SPECKLE, SHADOW_C) + [("path", {"d": stamp_path("293"), "fill": INK})]
        with open(os.path.join(preview, "egg_stamped.svg"), "w") as f:
            f.write(svg(EGG_W, EGG_H, stamped, size=(544, 544)))
    print(f"wrote {len(files)} drawables and art/play-icon.svg")


if __name__ == "__main__":
    main()
